# Run from extracted application root: source('tests/test_published_powdery_mildew.R')
source('models.R');source('advanced_models.R')
d <- read.csv('examples/PowderyMildew_published.csv')
a <- pe_audpc_groups(d)
stopifnot(nrow(d)==240L,nrow(a)==24L)
x <- subset(a,treatment=='Drip' & moisture=='High moisture' & replicate==1)
stopifnot(nrow(x)==1L,abs(x$AUDPC-1299.55)<1e-7,abs(x$rAUDPC-1299.55/6300)<1e-10)
s <- subset(d,treatment=='Drip' & moisture=='High moisture' & replicate==1)
f <- pe_compare(s)
stopifnot(nrow(f$comparison)>=1,all(is.finite(f$comparison$RMSE_pct)),all(f$comparison$n==10))
print(f$comparison)
print(pe_holdout(s,f$best$model))
print(pe_crossing(f$best,50,max(s$time),30))
cat('Published PowderyMildew regression tests passed.\n')
